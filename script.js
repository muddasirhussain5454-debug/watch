/* =========================================
   FORMAT PRICE
========================================= */

function formatPrice(price) {

    return "Rs. " + price.toLocaleString("en-PK");

}


/* =========================================
   SAVE CART
========================================= */

function saveCart() {

    localStorage.setItem(
        "albertoCart",
        JSON.stringify(cart)
    );

}


/* =========================================
   DISPLAY PRODUCTS
========================================= */

function displayProducts(filter = "all") {

    productsContainer.innerHTML = "";

    const filtered = filter === "all"
        ? watches
        : watches.filter(watch => watch.category === filter);


    filtered.forEach(watch => {

        const product = document.createElement("article");

        product.className = "product";

        product.innerHTML = `

            <div class="product-image">

                <span class="badge">
                    ${watch.badge}
                </span>

                <img
                    src="${watch.image}"
                    alt="${watch.name}"
                    loading="lazy">

                <div class="product-actions">

                    <button
                        class="wishlist-btn"
                        title="Wishlist">

                        <i class="fa-regular fa-heart"></i>

                    </button>

                    <button
                        class="quick-view"
                        data-id="${watch.id}"
                        title="Quick View">

                        <i class="fa-regular fa-eye"></i>

                    </button>

                </div>


                <button
                    class="add-cart"
                    data-id="${watch.id}">

                    Add To Cart

                </button>


                <button
                    class="buy-now"
                    data-id="${watch.id}">

                    Buy Now

                </button>

            </div>


            <div class="product-info">

                <div class="product-brand">
                    ${watch.brand}
                </div>

                <div class="product-title">
                    ${watch.name}
                </div>

                <div class="rating">
                    ★★★★★
                </div>

                <div class="price">
                    ${formatPrice(watch.price)}
                </div>

            </div>

        `;


        productsContainer.appendChild(product);

    });


    attachProductButtons();

}


/* =========================================
   PRODUCT BUTTONS
========================================= */

function attachProductButtons() {

    document.querySelectorAll(".add-cart").forEach(button => {

        button.addEventListener("click", () => {

            const id = Number(button.dataset.id);

            addToCart(id);

        });

    });


    document.querySelectorAll(".buy-now").forEach(button => {

        button.addEventListener("click", () => {

            const id = Number(button.dataset.id);

            buyNow(id);

        });

    });


    document.querySelectorAll(".quick-view").forEach(button => {

        button.addEventListener("click", () => {

            const id = Number(button.dataset.id);

            showQuickView(id);

        });

    });

}


/* =========================================
   ADD TO CART
========================================= */

function addToCart(id) {

    const watch = watches.find(item => item.id === id);

    if (!watch) return;


    const existing = cart.find(item => item.id === id);


    if (existing) {

        existing.quantity += 1;

    } else {

        cart.push({
            id: watch.id,
            quantity: 1
        });

    }


    saveCart();

    updateCart();

    showToast(
        `${watch.name} added to cart`
    );

}


/* =========================================
   UPDATE CART
========================================= */

function updateCart() {

    let totalQuantity = 0;
    let totalPrice = 0;


    cartItems.innerHTML = "";


    if (cart.length === 0) {

        cartItems.innerHTML = `
            <div class="empty-cart">
                <i class="fa-solid fa-bag-shopping"></i>
                <p>Your shopping bag is empty.</p>
            </div>
        `;

    }


    cart.forEach(item => {

        const watch = watches.find(
            product => product.id === item.id
        );

        if (!watch) return;


        totalQuantity += item.quantity;

        totalPrice += watch.price * item.quantity;


        const cartItem = document.createElement("div");

        cartItem.className = "cart-item";


        cartItem.innerHTML = `

            <img
                src="${watch.image}"
                alt="${watch.name}">

            <div>

                <h4>
                    ${watch.name}
                </h4>

                <p>
                    ${formatPrice(watch.price)}
                </p>

                <div class="cart-controls">

                    <button
                        onclick="changeQuantity(${watch.id}, -1)">
                        −
                    </button>

                    <strong>
                        ${item.quantity}
                    </strong>

                    <button
                        onclick="changeQuantity(${watch.id}, 1)">
                        +
                    </button>

                    <button
                        class="remove-item"
                        onclick="removeFromCart(${watch.id})">

                        <i class="fa-solid fa-trash"></i>

                    </button>

                </div>

            </div>

        `;


        cartItems.appendChild(cartItem);

    });


    cartCount.textContent = totalQuantity;

    cartTotal.textContent = formatPrice(totalPrice);

    saveCart();

}


/* =========================================
   CHANGE QUANTITY
========================================= */

function changeQuantity(id, amount) {

    const item = cart.find(
        product => product.id === id
    );

    if (!item) return;


    item.quantity += amount;


    if (item.quantity <= 0) {

        cart = cart.filter(
            product => product.id !== id
        );

    }


    updateCart();

}


/* =========================================
   REMOVE
========================================= */

function removeFromCart(id) {

    cart = cart.filter(
        product => product.id !== id
    );

    updateCart();

    showToast("Item removed from cart");

}


/* =========================================
   BUY NOW
========================================= */

function buyNow(id) {

    const watch = watches.find(
        product => product.id === id
    );

    if (!watch) return;


    orderWatch.value = watch.id;

    orderQuantity.value = 1;

    calculateOrderTotal();


    document.getElementById("contact")
        .scrollIntoView({
            behavior: "smooth"
        });


    setTimeout(() => {

        document.getElementById("customerName")
            .focus();

    }, 700);

}


/* =========================================
   ORDER WATCH DROPDOWN
========================================= */

function loadOrderWatches() {

    orderWatch.innerHTML = `
        <option value="">
            Select a watch
        </option>
    `;


    watches.forEach(watch => {

        const option = document.createElement("option");

        option.value = watch.id;

        option.textContent =
            `${watch.brand} — ${watch.name} — ${formatPrice(watch.price)}`;

        orderWatch.appendChild(option);

    });

}


/* =========================================
   CALCULATE ORDER TOTAL
========================================= */

function calculateOrderTotal() {

    const id = Number(orderWatch.value);

    const quantity =
        Number(orderQuantity.value) || 1;


    const watch = watches.find(
        item => item.id === id
    );


    if (!watch) {

        orderTotal.textContent = "Rs. 0";

        return;

    }


    const total =
        watch.price * quantity;


    orderTotal.textContent =
        formatPrice(total);

}


/* =========================================
   PAYMENT METHOD
========================================= */

paymentMethod.addEventListener(
    "change",
    function () {

        const method = this.value;


        if (!method) {

            paymentInfo.classList.remove("show");

            return;

        }


        paymentInfo.classList.add("show");


        if (method === "Cash on Delivery") {

            paymentText.textContent =
                "Pay cash when your watch is delivered to your address.";

        }


        else if (method === "Easypaisa") {

            paymentText.textContent =
                "Easypaisa: 0300-1234567 — Please send payment and keep your transaction ID.";

        }


        else if (method === "JazzCash") {

            paymentText.textContent =
                "JazzCash: 0300-1234567 — Please send payment and keep your transaction ID.";

        }


        else if (method === "Bank Transfer") {

            paymentText.textContent =
                "Bank transfer details will be provided by Alberto Watches after order confirmation.";

        }

    }
);


